#!/usr/bin/env bash
# Build, or re-converge, the disposable Moodle integration-test site.
# Idempotent: every step checks state first, so re-running is safe.
#
#   ./setup.sh            # first run: download, install, configure, seed
#   MOODLE_PORT=8097 ./setup.sh   # pick the port yourself (first run only)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

TARBALL=moodle-latest-500.tgz
TARBALL_URL="https://download.moodle.org/download.php/direct/stable500/${TARBALL}"
CODE_DIR="$HERE/moodle"
DL_DIR="$HERE/dl"

log() { printf '[setup] %s\n' "$*" >&2; }
die() { printf '[setup] ERROR: %s\n' "$*" >&2; exit 1; }
compose() { docker compose -p moodle-it -f "$HERE/docker-compose.yml" "$@"; }
moodle_php() { compose exec -T -u www-data -w /var/www/html web php "$@"; }

command -v docker >/dev/null || die "docker not found"
docker compose version >/dev/null 2>&1 || die "docker compose plugin not found"

# ---------------------------------------------------------------- 1. .env
randpw() {
    # 16 random alphanumerics around a fixed "-Aa1", so Moodle's default
    # password policy (upper, lower, digit, symbol) is always met.
    local r
    r="$(head -c 48 /dev/urandom | base64 -w0 | tr -dc 'A-Za-z0-9' | cut -c1-16)"
    printf '%s-Aa1%s' "${r:0:8}" "${r:8:8}"
}
port_in_use() {
    if command -v ss >/dev/null; then
        ss -Hltn "sport = :$1" | grep -q .
    else
        (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
    fi
}

if [ ! -f .env ]; then
    port="${MOODLE_PORT:-}"
    if [ -z "$port" ]; then
        for p in 8099 8098 8097 8096 8095; do
            if ! port_in_use "$p"; then port=$p; break; fi
        done
        [ -n "$port" ] || die "ports 8095-8099 are all busy; set MOODLE_PORT"
    elif port_in_use "$port"; then
        die "port $port is already in use"
    fi
    log "generating .env (web port 127.0.0.1:$port)"
    (
        umask 077
        cat > .env <<EOF
# Generated by setup.sh on $(date -u +%FT%TZ). Disposable test credentials. Never commit.
MOODLE_PORT=$port
MOODLE_WWWROOT=http://localhost:$port
MOODLE_DB_PASSWORD=$(randpw)
MOODLE_ADMIN_USER=admin
MOODLE_ADMIN_PASSWORD=$(randpw)
MOODLE_STUDENT1_PASSWORD=$(randpw)
MOODLE_STUDENT2_PASSWORD=$(randpw)
MOODLE_TEACHER1_PASSWORD=$(randpw)
EOF
    )
fi
chmod 600 .env
set -a; . ./.env; set +a

# ---------------------------------------------------------------- 2. code
verify_tarball() {
    [ -s "$DL_DIR/$TARBALL" ] && [ -s "$DL_DIR/$TARBALL.sha256" ] || return 1
    local want got
    want="$(grep -oE '[0-9a-f]{64}' "$DL_DIR/$TARBALL.sha256" | head -n1)"
    got="$(sha256sum "$DL_DIR/$TARBALL" | cut -d' ' -f1)"
    [ -n "$want" ] && [ "$want" = "$got" ]
}

if [ -f "$CODE_DIR/version.php" ]; then
    log "code present: Moodle $(sed -n "s/^\$release *= *'\([^']*\)'.*/\1/p" "$CODE_DIR/version.php")"
else
    mkdir -p "$DL_DIR"
    if verify_tarball; then
        log "using cached $TARBALL (sha256 OK)"
    else
        log "downloading $TARBALL_URL"
        curl -fsSL --retry 3 -o "$DL_DIR/$TARBALL.sha256.part" "$TARBALL_URL.sha256"
        curl -fSL --retry 3 --progress-bar -o "$DL_DIR/$TARBALL.part" "$TARBALL_URL"
        mv "$DL_DIR/$TARBALL.sha256.part" "$DL_DIR/$TARBALL.sha256"
        mv "$DL_DIR/$TARBALL.part" "$DL_DIR/$TARBALL"
        verify_tarball || die "sha256 mismatch for $TARBALL"
        log "sha256 OK"
    fi
    rm -rf "$CODE_DIR.tmp"
    mkdir -p "$CODE_DIR.tmp"
    tar -xzf "$DL_DIR/$TARBALL" -C "$CODE_DIR.tmp" --strip-components=1
    # Moodle 5.1+ moved the web root to public/. This setup targets 5.0.
    [ ! -d "$CODE_DIR.tmp/public" ] || die "tarball has a public/ web root; this setup expects the 5.0 layout"
    mv "$CODE_DIR.tmp" "$CODE_DIR"
    log "extracted Moodle $(sed -n "s/^\$release *= *'\([^']*\)'.*/\1/p" "$CODE_DIR/version.php")"
fi

# ---------------------------------------------------------------- 3. containers
log "starting containers (project moodle-it)"
compose up -d --wait
for _ in $(seq 1 60); do
    compose exec -T db pg_isready -q -U moodle -d moodle && break
    sleep 2
done
compose exec -T db pg_isready -q -U moodle -d moodle || die "postgres did not become ready"

# ---------------------------------------------------------------- 4. install
db_installed() {
    [ "$(compose exec -T db psql -U moodle -d moodle -tAc \
        "SELECT to_regclass('public.mdl_config') IS NOT NULL")" = "t" ]
}

if db_installed && [ -f "$CODE_DIR/config.php" ]; then
    log "already installed; running upgrade.php (no-op unless something is pending)"
    moodle_php admin/cli/upgrade.php --non-interactive | tail -n 1
elif db_installed; then
    die "database is installed but config.php is missing; run ./teardown.sh and then ./setup.sh"
else
    if [ -f "$CODE_DIR/config.php" ]; then
        log "removing stale config.php (database is empty)"
        rm -f "$CODE_DIR/config.php"
    fi
    log "installing Moodle (a few minutes)"
    # install.php runs as www-data and must be able to create config.php.
    chmod 0777 "$CODE_DIR"
    trap 'chmod 0755 "$CODE_DIR"' EXIT
    moodle_php admin/cli/install.php --non-interactive --agree-license --lang=en \
        --wwwroot="$MOODLE_WWWROOT" --dataroot=/var/www/moodledata \
        --dbtype=pgsql --dbhost=db --dbname=moodle --dbuser=moodle \
        --dbpass="$MOODLE_DB_PASSWORD" --prefix=mdl_ \
        --fullname="Moodle IT (disposable test site)" --shortname="moodle-it" \
        --summary="Disposable integration-test site. All data is fictional." \
        --adminuser="$MOODLE_ADMIN_USER" --adminpass="$MOODLE_ADMIN_PASSWORD" \
        --adminemail=admin@example.com --supportemail=support@example.com \
        > "$HERE/install.log" 2>&1 || { tail -n 30 "$HERE/install.log" >&2; die "install.php failed (see install.log)"; }
    chmod 0755 "$CODE_DIR"
    trap - EXIT
    log "installed ($(grep -c . "$HERE/install.log") log lines in install.log)"
fi

# ---------------------------------------------------------------- 5. config
log "applying site configuration"
moodle_php /opt/moodle-it/configure.php

# ---------------------------------------------------------------- 6. seed
set +e
moodle_php /opt/moodle-it/seed.php --check >/dev/null 2>&1
rc=$?
set -e
case "$rc" in
    0)
        if [ -s seed-ids.json ]; then
            log "already seeded (seed-ids.json present)"
        else
            log "already seeded; re-exporting seed-ids.json"
            moodle_php /opt/moodle-it/seed.php --dump > seed-ids.json.tmp
            mv seed-ids.json.tmp seed-ids.json
        fi
        ;;
    3)
        log "seeding test data"
        compose exec -T -u www-data -w /var/www/html \
            -e MOODLE_STUDENT1_PASSWORD -e MOODLE_STUDENT2_PASSWORD -e MOODLE_TEACHER1_PASSWORD \
            web php /opt/moodle-it/seed.php > seed-ids.json.tmp \
            || { cat seed-ids.json.tmp >&2; rm -f seed-ids.json.tmp; die "seed.php failed (nothing was committed)"; }
        mv seed-ids.json.tmp seed-ids.json
        ;;
    *)
        die "seed.php --check failed (exit $rc)"
        ;;
esac

# ---------------------------------------------------------------- done
curl -fsS -o /dev/null "$MOODLE_WWWROOT/login/index.php" || die "$MOODLE_WWWROOT/login/index.php is not answering"
log "ready: $MOODLE_WWWROOT (bound to 127.0.0.1 only)"
log "credentials: $HERE/.env"
log "ids:         $HERE/seed-ids.json"
